// Builds the learner pages' browser code (src/learner/browser) into static files:
// - render, code, math: classic scripts (*.browser.js with marked + DOMPurify, highlight.js, temml),
//   loaded by the page (code and math only when a reply needs them); workspace, a page's panels beside
//   the chat (only on pages that have them);
// - diagram-*.html and its code-split ES modules: Mermaid, run in a sandboxed, network-less frame;
// - pdf, pdf-worker and pdf-VERSION/: pdf.js for activities with a Reading panel (the library as a
//   classic script, its worker module, and the character maps, fonts and image decoders it fetches).
// Every file name carries a content hash, so it can be cached for good. A host serves them under
// /v1/agents/chat-assets/, and passes the names to the pages (manifest.json here).
// The output holds third-party libraries (NOTICE) and isn't kept in this repository: `npm run
// build:assets` writes it to dist/, which a package and an image carry.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { FRAME_CSP } from '../src/learner/shell.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = `${root}src/learner/browser`;
export const ASSET_ROUTE = 'v1/agents/chat-assets';
const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 12);
const common = { bundle: true, minify: true, target: ['es2022'], legalComments: 'eof', write: false, logLevel: 'silent', preserveSymlinks: true };

/** What a static host serves them with (Cloudflare's and Netlify's _headers format). */
export const HEADERS = `# Generated by scripts/build-learner-assets.mjs.
/${ASSET_ROUTE}/*
  Cache-Control: public, max-age=31536000, immutable
  X-Content-Type-Options: nosniff
  Access-Control-Allow-Origin: *

/${ASSET_ROUTE}/diagram-*.html
  Content-Security-Policy: ${FRAME_CSP}
  X-Robots-Tag: noindex
  Referrer-Policy: no-referrer

/v1/agents/chat-render.json
  Cache-Control: public, max-age=300
  X-Content-Type-Options: nosniff
  Access-Control-Allow-Origin: *
`;
/** The renderer's files by their paths on the host, for pages elsewhere (a dashboard) to load. */
export const renderSource = (names) => `${JSON.stringify(Object.fromEntries(['render', 'code', 'math', 'diagram'].map((key) => [key, `/${ASSET_ROUTE}/${names[key]}`])), null, 2)}\n`;

/**
 * Every output file ({path relative to the assets' folder: contents}) and the manifest of names.
 * workingDir: what the libraries' paths are relative to, which their chunks' hashed names depend on.
 */
export async function bundleChatAssets({ workingDir = root } = {}) {
  const files = {};
  const names = {};
  const options = { ...common, absWorkingDir: workingDir };
  for (const name of ['render', 'code', 'math', 'workspace']) {
    const result = await build({ ...options, entryPoints: [`${SOURCE}/${name}.browser.js`], format: 'iife' });
    const code = result.outputFiles[0].text;
    names[name] = `${name}-${hash(code)}.js`;
    files[names[name]] = code;
  }
  const diagram = await build({ ...options, entryPoints: [`${SOURCE}/diagram.browser.js`], format: 'esm', splitting: true, outdir: ASSET_ROUTE, entryNames: 'diagram-[hash]', chunkNames: 'chunk-[hash]' });
  let entry = '';
  for (const output of diagram.outputFiles) {
    const file = output.path.slice(output.path.lastIndexOf('/') + 1);
    files[file] = output.text;
    if (file.startsWith('diagram-')) entry = file;
  }
  const page = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Diagram renderer</title><meta name="robots" content="noindex"><script type="module" src="${entry}"></script></head><body></body></html>\n`;
  names.diagram = `diagram-${hash(page)}.html`;
  files[names.diagram] = page;
  const pdf = (await build({ ...options, entryPoints: [`${SOURCE}/pdf.browser.js`], format: 'iife' })).outputFiles[0].text;
  names.pdf = `pdf-${hash(pdf)}.js`;
  files[names.pdf] = pdf;
  const library = new URL('.', `file://${createRequire(`${root}/`).resolve('pdfjs-dist/package.json')}`);
  const worker = await readFile(new URL('build/pdf.worker.min.mjs', library), 'utf8');
  names.pdfWorker = `pdf-worker-${hash(worker)}.mjs`;
  files[names.pdfWorker] = worker;
  const { version } = JSON.parse(await readFile(new URL('package.json', library), 'utf8'));
  names.pdfData = `pdf-${version}/`;
  // Scripting in PDFs (QuickJS) isn't used: the panel turns it off.
  for (const dir of ['cmaps', 'standard_fonts', 'wasm']) {
    for (const file of (await readdir(new URL(`${dir}/`, library))).sort()) if (!/^LICENSE|quickjs/i.test(file)) files[`${names.pdfData}${dir}/${file}`] = await readFile(new URL(`${dir}/${file}`, library));
  }
  return { files, names };
}

/** Writes the assets under folder as a host serves them, replacing what was there; returns { files, names }. */
export async function writeChatAssets(folder, options) {
  const { files, names } = await bundleChatAssets(options);
  const dir = `${folder}/${ASSET_ROUTE}/`;
  await rm(dir, { recursive: true, force: true });
  for (const [file, text] of Object.entries(files)) { await mkdir(dirname(`${dir}${file}`), { recursive: true }); await writeFile(`${dir}${file}`, text); }
  await writeFile(`${folder}/_headers`, HEADERS);
  await writeFile(`${folder}/v1/agents/chat-render.json`, renderSource(names));
  return { files, names };
}

// What answers a static copy of demo mode (src/try/static.browser.js), which `viable-harness try --export`
// writes into the copy. Its pages are already written, so what only draws a page stays out: 1.3 MB of it.
const LEFT_OUT = { 'misconceptionsData.js': 'export const CONSTRUCTS = "", MISCONCEPTIONS = "";', 'catalogData.js': 'export const CATALOG = [];', 'fontData.js': 'export const NEXT = "", MONO = "";' };
const leaveOut = { name: 'leave-out', setup(on) { on.onLoad({ filter: /(?:misconceptionsData|catalogData|fontData)\.js$/ }, ({ path }) => ({ contents: LEFT_OUT[path.slice(path.lastIndexOf('/') + 1)], loader: 'js' })); } };
const writeTryStatic = () => build({ absWorkingDir: root, entryPoints: ['src/try/static.browser.js'], outfile: 'dist/try/app.js', bundle: true, format: 'esm', minify: true, target: ['es2022'], platform: 'browser', legalComments: 'eof', logLevel: 'error', preserveSymlinks: true, plugins: [leaveOut] });

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeTryStatic();
  const { files, names } = await writeChatAssets(`${root}dist`);
  await writeFile(`${root}dist/${ASSET_ROUTE}/manifest.json`, `${JSON.stringify(names, null, 2)}\n`);
  const total = Object.values(files).reduce((sum, text) => sum + text.length, 0);
  console.log(`${Object.keys(files).length} files, ${(total / 1048576).toFixed(2)} MiB, in dist/.`);
}
