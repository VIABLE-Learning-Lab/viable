// Writes the step manifests (src/agents/steps) for the harness kit and, when the sibling checkout is
// there, the Developer Portal. Run with `npm run steps:build`; never edit either copy by hand.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STEP_MANIFESTS } from '../src/agents/steps/index.js';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const kitPath = resolve(repoRoot, 'kit', 'schemas', 'steps.json');
export const portalPath = resolve(repoRoot, '..', 'viablelab-developers', 'app', 'data', 'stepManifests.generated.ts');

const json = () => JSON.stringify({ object: 'agent.step_manifests', version: 1, steps: STEP_MANIFESTS }, null, 2);
export const kitText = () => `${json()}\n`;
// A module, not .json: the portal's Node test runner can't import JSON without import attributes.
export const portalText = () => `// Generated by viablelab-api: npm run steps:build. Do not edit.\nexport default ${json()}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(kitPath, kitText());
  console.log(`Wrote ${kitPath}`);
  if (existsSync(dirname(portalPath))) {
    writeFileSync(portalPath, portalText());
    console.log(`Wrote ${portalPath}`);
  } else {
    console.log(`Skipped the portal copy: ${dirname(portalPath)} is missing.`);
  }
}
