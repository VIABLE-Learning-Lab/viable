// Builds src/utils/skillsData.js, the Carnegie Skills Progressions as VIABLE keeps them, from a
// Learning Commons Knowledge Graph release (nodes.jsonl and relationships.jsonl, CC BY 4.0).
// Learning Commons' REST search doesn't cover durable skills yet, so VIABLE carries its own copy.
//   node scripts/build-skills-data.mjs /path/to/open-knowledge-graph
import { createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the folder that holds nodes.jsonl and relationships.jsonl.');
const FRAMEWORK = 'Carnegie Skills Progressions';

async function* lines(file) {
  for await (const line of createInterface({ input: createReadStream(`${dir}/${file}`), crlfDelay: Infinity })) if (line.trim()) yield JSON.parse(line);
}

const nodes = new Map();
let framework = null;
for await (const node of lines('nodes.jsonl')) {
  const props = node.properties || node;
  const label = (node.labels || [node.label])[0];
  if (label === 'StandardsFramework' && props.name === FRAMEWORK) framework = props;
  if (label === 'StandardsFrameworkItem' && props.academicSubject === 'Durable Skills') nodes.set(props.identifier, props);
}
if (!framework) throw new Error(`${FRAMEWORK} isn't in this release.`);
const children = new Map();
for await (const edge of lines('relationships.jsonl')) {
  if (edge.label !== 'hasChild') continue;
  if (edge.source_identifier !== framework.identifier && !nodes.has(edge.source_identifier)) continue;
  children.set(edge.source_identifier, [...(children.get(edge.source_identifier) || []), edge.target_identifier]);
}
const kids = (id) => (children.get(id) || []).map((child) => nodes.get(child)).filter(Boolean).sort((a, b) => a.statementCode.localeCompare(b.statementCode, 'en', { numeric: true }));
const LEVELS = ['Exploring', 'Analyzing', 'Integrating', 'Extending'];

const skills = kids(framework.identifier).map((skill) => ({
  code: skill.statementCode, name: skill.name, description: skill.description,
  subskills: kids(skill.identifier).map((subskill) => ({
    code: subskill.statementCode, description: subskill.description,
    indicators: kids(subskill.identifier).map((indicator) => ({
      id: indicator.identifier, code: indicator.statementCode, description: indicator.description,
      // Each item: its four levels, Exploring to Extending, as [id, what a learner at that level does].
      items: kids(indicator.identifier).map((item) => ({
        code: item.statementCode,
        levels: LEVELS.map((name) => kids(item.identifier).find((level) => level.name === name)).map((level) => (level ? [level.identifier, level.description] : null))
      })).filter((item) => item.levels.every(Boolean))
    })).filter((indicator) => indicator.items.length)
  }))
}));

const data = {
  framework: { id: framework.identifier, name: framework.name, author: framework.author, description: framework.description, license: framework.license, attribution: framework.attributionStatement, modified: framework.dateModified },
  levels: LEVELS,
  skills
};
const count = skills.flatMap((skill) => skill.subskills.flatMap((subskill) => subskill.indicators)).length;
writeFileSync(new URL('../src/utils/skillsData.js', import.meta.url), `// Generated by scripts/build-skills-data.mjs from a Learning Commons Knowledge Graph release. Don't edit.
// ${framework.name}, ${framework.author}, via Learning Commons, CC BY 4.0: ${framework.attributionStatement}
export const SKILLS = ${JSON.stringify(data)};
`);
console.log(`${count} indicators in ${skills.length} skills.`);
