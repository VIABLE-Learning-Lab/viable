// Writes docs/catalog.md and src/utils/catalogData.js (what searchCatalog reads) from catalog/*.json,
// one file per public good (schemas/catalog-entry.schema.json). Run with `npm run catalog:build`;
// never edit either by hand.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const catalogDir = fileURLToPath(new URL('../catalog/', import.meta.url));
export const pagePath = fileURLToPath(new URL('../docs/catalog.md', import.meta.url));
export const modulePath = fileURLToPath(new URL('../src/utils/catalogData.js', import.meta.url));
// The kinds in the schema's order, which is the page's.
const KINDS = JSON.parse(readFileSync(new URL('../schemas/catalog-entry.schema.json', import.meta.url), 'utf8')).properties.kind.enum;
const HEADINGS = {
  'knowledge-graph': 'Knowledge graphs', standards: 'Standards and progressions', content: 'Open content', dataset: 'Datasets',
  benchmark: 'Benchmarks', evaluator: 'Evaluators', model: 'Models', tool: 'Tools', 'learning-data-repository': 'Learning data repositories'
};
const cell = (value) => String(value).replace(/\|/g, '\\|');

/** Every entry in catalog/, by kind and then by name. */
export const catalogEntries = () => readdirSync(catalogDir).filter((name) => name.endsWith('.json')).sort()
  .map((name) => JSON.parse(readFileSync(`${catalogDir}${name}`, 'utf8')))
  .sort((a, b) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || a.name.localeCompare(b.name, 'en'));

export const catalogModule = (entries) => `// Generated by scripts/build-catalog-page.mjs from catalog/*.json. Don't edit.
export const CATALOG = ${JSON.stringify(entries, null, 2)};
`;

const LEVELS = ['Listed', 'Fetchable', 'Connected', 'Built in'];
// In the order the page leads with: what runs against an agent first.
const AS = { 'test-suite': 'test suite', judge: 'judge', 'calibration-set': 'calibration set', 'context-lookup': 'context lookup', 'knowledge-folder': 'knowledge folder', measure: 'measure', step: 'step' };
const asOrder = (entry) => Object.keys(AS).indexOf(entry.connect.as[0]);

function connectedRow(entry) {
  const { command, note, as } = entry.connect;
  return [`[${entry.name}](${entry.url})`, as.map((item) => AS[item]).join(', ') || '', `\`${command}\``, note, entry.license.spdx.join(', ') + (entry.license.unclear ? ' (unclear)' : '')].map(cell).join(' | ');
}

function row(entry) {
  const { license, fits, connect } = entry;
  const ids = license.spdx.length ? license.spdx.join(', ') : 'none stated';
  return [
    `[${entry.name}](${entry.url}): ${entry.summary}`,
    `${entry.subjects.join(', ')}; grades ${entry.grades}`,
    `${ids}${license.unclear ? ' (unclear)' : ''}${license.note ? `. ${license.note}` : ''}`,
    `${entry.access}${entry.access_note ? `. ${entry.access_note}` : ''}${entry.expected ? ` Expected: ${entry.expected}` : ''}`,
    `${fits.slots.length ? `${fits.slots.join(', ')}: ` : ''}${fits.how}${entry.in_harness ? ` Built in: [\`${entry.in_harness}\`](components/${entry.in_harness.replace('/', '-')}.md).` : ''}`,
    LEVELS[connect.level],
    entry.verified_at
  ].map(cell).join(' | ');
}

export function catalogPage(entries) {
  const count = (test) => entries.filter(test).length;
  return [
    '# Public goods catalog',
    '',
    '<!-- Written from catalog/*.json by npm run catalog:build; don’t edit by hand. -->',
    '',
    `${count((entry) => entry.connect.level === 2)} of these ${entries.length} public goods are one command from having an effect on your agent, and ${count((entry) => entry.connect.level === 3)} are built in. ${count((entry) => entry.connect.level === 1)} only come down, and ${count((entry) => entry.connect.level === 0)} are listed, each saying why it goes no further. [resources.md](resources.md) says what connected means.`,
    '',
    ...[[2, 'Connected', 'The first time, each command fetches its source to `~/.viable-harness/resources/<id>/` from its makers, shows its license, and asks you to accept it where it limits use.'], [3, 'Built in', 'In the core, with no download.'], [1, 'Fetchable', '`viable-harness resources get <id>` brings down the files and records what came; nothing is made from them yet.']].flatMap(([level, heading, line]) => [
      `## ${heading}`,
      '',
      line,
      '',
      '| Public good | Connects as | Command | What it can show, and what it can’t | License |',
      '| --- | --- | --- | --- | --- |',
      ...entries.filter((entry) => entry.connect.level === level).sort((a, b) => asOrder(a) - asOrder(b)).map((entry) => `| ${connectedRow(entry)} |`),
      ''
    ]),
    '## Every entry',
    '',
    'Open datasets, benchmarks, knowledge graphs, standards, evaluators, models, tools, open content and',
    'learning data repositories for K-12 AI, each with its license, how to get it, and the harness slot',
    'it would fill ([components.md](components.md)). Entries describe; they don’t endorse. Each says',
    'what its primary sources (its own site, repository, license file, dataset card or paper) stated on',
    'the date in its last column: check the license yourself before you use one, and keep its',
    'attribution.',
    '',
    'Search it with `viable-harness catalog [words...] [--kind <kind>] [--slot <slot>] [--open] [--connected] [--json]`,',
    'with `searchCatalog(query, { kind, slot, open, connected })` from the package, or with the MCP server’s',
    '`find_public_goods` tool ([mcp.md](mcp.md)). `--open` keeps what anyone can download without asking',
    'and use, commercially too, under every license listed; an entry’s note can still leave parts out.',
    '`--connected` keeps what has an effect on an agent. To add an entry or correct one, see',
    '[CONTRIBUTING.md](../../CONTRIBUTING.md#catalog-entries).',
    '',
    `${entries.length} entries: ${count((entry) => entry.in_harness)} built into the harness, ${count((entry) => entry.status === 'expected')} not yet released.`,
    '',
    ...KINDS.filter((kind) => entries.some((entry) => entry.kind === kind)).flatMap((kind) => [
      `### ${HEADINGS[kind]}`,
      '',
      '| Public good | Subjects and grades | License | Access | Fits | Level | Checked |',
      '| --- | --- | --- | --- | --- | --- | --- |',
      ...entries.filter((entry) => entry.kind === kind).map((entry) => `| ${row(entry)} |`),
      ''
    ])
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = catalogEntries();
  writeFileSync(modulePath, catalogModule(entries));
  writeFileSync(pagePath, catalogPage(entries));
  console.log(`Wrote ${entries.length} entries to ${pagePath} and ${modulePath}`);
}
