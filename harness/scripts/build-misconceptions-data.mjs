// Builds src/utils/misconceptionsData.js (and misconceptionsSource.js): Eedi's math misconceptions and the constructs (the skills
// they hinder), from a Learning Commons Knowledge Graph release (nodes.jsonl and relationships.jsonl,
// CC BY 4.0). The open release doesn't link constructs to standards (that part is gated), so VIABLE
// matches them by their words (standards.js). Only ids and descriptions are kept.
//   node scripts/build-misconceptions-data.mjs /path/to/open-knowledge-graph
import { createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the folder that holds nodes.jsonl and relationships.jsonl.');

async function* lines(file, needle) {
  // Most of the release is other data: only lines naming what we keep are parsed.
  for await (const line of createInterface({ input: createReadStream(`${dir}/${file}`), crlfDelay: Infinity })) if (line.includes(needle)) yield JSON.parse(line);
}

const misconceptions = new Map();
const constructs = new Map();
let source = null;
for await (const node of lines('nodes.jsonl', 'Eedi')) {
  const props = node.properties || {};
  const label = (node.labels || [])[0];
  if (label !== 'Misconception' && label !== 'Construct') continue;
  (label === 'Misconception' ? misconceptions : constructs).set(props.identifier, props.description);
  source ||= props;
}
if (!source || !misconceptions.size) throw new Error('Eedi misconceptions aren’t in this release.');
const hinders = new Map();
for await (const edge of lines('relationships.jsonl', '"hinders"')) {
  if (edge.label !== 'hinders' || !misconceptions.has(edge.source_identifier) || !constructs.has(edge.target_identifier)) continue;
  hinders.set(edge.target_identifier, [...(hinders.get(edge.target_identifier) || []), edge.source_identifier]);
}

// Compact strings, decoded on first use (standards.js): records split by `, fields by ~ (neither is in
// Eedi's text). Misconceptions: id~description, ids as 32 hex digits (dashes put back on reading).
// Constructs: id~description~the indexes of the misconceptions that hinder it (base 36, by commas).
const clean = (value) => String(value).replace(/\s+/g, ' ').trim();
const hex = (id) => id.replace(/-/g, '');
const byText = (a, b) => a[1].localeCompare(b[1], 'en');
const kept = [...misconceptions].map(([id, description]) => [id, clean(description)]).sort(byText);
const index = new Map(kept.map(([id], i) => [id, i]));
const listed = [...constructs].filter(([id]) => hinders.has(id)).map(([id, description]) => [id, clean(description)]).sort(byText);
for (const [, description] of [...kept, ...listed]) if (/[`~]/.test(description)) throw new Error(`A description holds a separator: ${description}`);
const misconceptionRows = kept.map(([id, description]) => `${hex(id)}~${description}`).join('`');
const constructRows = listed.map(([id, description]) => `${hex(id)}~${description}~${[...new Set(hinders.get(id))].map((m) => index.get(m)).sort((a, b) => a - b).map((i) => i.toString(36)).join(',')}`).join('`');
const name = /"([^"]+)"/.exec(source.attributionStatement)?.[1] || 'Eedi Misconceptions Graph';
const header = `// Generated by scripts/build-misconceptions-data.mjs from a Learning Commons Knowledge Graph release. Don't edit.
// ${name}, ${source.author}, via Learning Commons, CC BY 4.0: ${source.attributionStatement}
`;
// The source alone, small, for what keeps a chosen misconception (teaching.js) without the data.
writeFileSync(new URL('../src/utils/misconceptionsSource.js', import.meta.url), `${header}export const MISCONCEPTIONS_SOURCE = ${JSON.stringify({ name, author: source.author, license: source.license, attribution: source.attributionStatement, modified: source.dateModified })};
`);
writeFileSync(new URL('../src/utils/misconceptionsData.js', import.meta.url), `${header}// Strings, decoded on first use (standards.js), so a Worker that never searches them never pays for it.
export const MISCONCEPTIONS = ${JSON.stringify(misconceptionRows)};
export const CONSTRUCTS = ${JSON.stringify(constructRows)};
`);
console.log(`${kept.length} misconceptions hindering ${listed.length} constructs (${[...hinders.values()].reduce((sum, list) => sum + list.length, 0)} links).`);
