// Builds src/ui/fontData.js from the font files in src/ui/fonts/, so a page or a Worker can have the
// fonts with no file system. The files are Google Fonts' latin subsets of Atkinson Hyperlegible Next
// and Mono (SIL OFL 1.1, the licences are beside them).
//   node scripts/build-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const FILES = { NEXT: 'atkinson-hyperlegible-next-latin.woff2', MONO: 'atkinson-hyperlegible-mono-latin.woff2' };
const dir = new URL('../src/ui/fonts/', import.meta.url);
const lines = Object.entries(FILES).map(([name, file]) => `export const ${name} = '${readFileSync(new URL(file, dir)).toString('base64')}';`);
writeFileSync(new URL('../src/ui/fontData.js', import.meta.url), `// Generated by scripts/build-fonts.mjs from src/ui/fonts/: don't edit. SIL OFL 1.1, see the licences there.\n${lines.join('\n')}\n`);
